package kg

import (
	"fmt"
	"path/filepath"
	"strings"
)

// ---------------------------------------------------------------------------
// KG_REPORT.md — graphify report.py section list
// ---------------------------------------------------------------------------

func writeReport(root string, graph *Graph) (string, error) {
	adj := buildAdjacency(graph)
	communities := graph.Communities
	gods := godNodes(graph, adj, 10)
	surprises := surprisingConnections(graph, adj, 10)
	cycles := importCycles(graph, 5)
	questions := suggestQuestions(graph, adj, communities, gods)
	byID := cmdByID(graph)
	pct := cmdConfidencePct(graph)

	L := []string{}
	push := func(s string) { L = append(L, s) }
	push("# Graph Report - " + cmdBasename(root))
	push("")
	push("_Generated by `draht-tools kg build`. Do not edit; regenerated each build._")
	push("")
	push("## Summary")
	push("")
	push(fmt.Sprintf("%d nodes · %d edges · %d communities", len(graph.Nodes), len(graph.Edges), len(communities)))
	push("")
	push(pct("EXTRACTED") + "% EXTRACTED · " + pct("INFERRED") + "% INFERRED · " + pct("AMBIGUOUS") + "% AMBIGUOUS")
	push("")
	push("## Community Hubs (Navigation)")
	push("")
	for i, c := range communities {
		if i >= 15 {
			break
		}
		push(fmt.Sprintf("- **%s** — community %d, %d nodes, cohesion %s", c.Name, c.ID, c.Size, jsNumber(c.Cohesion)))
	}
	push("")
	push("## God Nodes")
	push("")
	push("| Node | Degree | Source |")
	push("| --- | --- | --- |")
	for _, g := range gods {
		sourceFile := g.SourceFile
		if sourceFile == "" {
			sourceFile = "-"
		}
		push("| `" + g.Label + "` | " + cmdNum(g.Degree) + " | " + sourceFile + " |")
	}
	push("")
	push("## Surprising Connections")
	push("")
	if len(surprises) > 0 {
		for _, s := range surprises {
			push("- `" + s.Source + "` --" + s.Relation + " [" + s.Confidence + "]--> `" + s.Target + "` (score " + cmdNum(s.Score) + "): " + strings.Join(s.Reasons, "; "))
		}
	} else {
		push("(none detected)")
	}
	push("")
	push("## Import Cycles")
	push("")
	if len(cycles) > 0 {
		for _, cyc := range cycles {
			labels := make([]string, 0, len(cyc))
			for _, id := range cyc {
				labels = append(labels, cmdLabel(byID, id))
			}
			push("- " + strings.Join(labels, " → "))
		}
	} else {
		push("(none — no file-level import cycles)")
	}
	push("")
	push("## Communities")
	push("")
	for _, c := range communities {
		if c.Size < 3 {
			continue
		}
		sample := []string{}
		for i, id := range c.Members {
			if i >= 8 {
				break
			}
			sample = append(sample, "`"+cmdLabel(byID, id)+"`")
		}
		push(fmt.Sprintf("### %s (community %d)", c.Name, c.ID))
		push("")
		push(fmt.Sprintf("%d nodes · cohesion %s", c.Size, jsNumber(c.Cohesion)))
		if len(sample) > 0 {
			more := ""
			if c.Size > 8 {
				more = " …"
			}
			push("Members: " + strings.Join(sample, ", ") + more)
		}
		push("")
	}
	push("## Ambiguous Edges - Review These")
	push("")
	amb := 0
	for _, e := range graph.Edges {
		if e.Confidence != "AMBIGUOUS" {
			continue
		}
		if amb >= 15 {
			break
		}
		amb++
		loc := ""
		if e.SourceLocation != "" {
			loc = ":" + e.SourceLocation
		}
		push("- `" + cmdLabel(byID, e.Source) + "` --" + e.Relation + "--> `" + cmdLabel(byID, e.Target) + "` (" + e.SourceFile + loc + ")")
	}
	if amb == 0 {
		push("(none)")
	}
	push("")
	push("## Knowledge Gaps")
	push("")
	isolated := []*Node{}
	for _, n := range graph.Nodes {
		if adj.deg.G(n.ID) == 0 && n.SourceFile != "" {
			isolated = append(isolated, n)
			if len(isolated) >= 10 {
				break
			}
		}
	}
	if len(isolated) > 0 {
		push(fmt.Sprintf("Isolated nodes (%d shown):", len(isolated)))
		for _, n := range isolated {
			push("- `" + n.Label + "` (" + n.SourceFile + ")")
		}
	} else {
		push("(no isolated nodes)")
	}
	push("")
	push("## Suggested Questions")
	push("")
	for _, q := range questions {
		push("- " + q)
	}
	push("")
	push("---")
	push("Query the graph: `draht-tools kg query \"<question>\"` · `kg explain \"<node>\"` · `kg path \"<a>\" \"<b>\"` · `kg affected \"<node>\"` · `kg export tree|wiki|graphml`.")
	push("")
	p := filepath.Join(outDir(root), "KG_REPORT.md")
	if err := cmdWriteIfChanged(p, strings.Join(L, "\n")); err != nil {
		return "", err
	}
	return p, nil
}
