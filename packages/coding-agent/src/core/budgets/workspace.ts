import { spawnSync } from "node:child_process";
import { existsSync, lstatSync, readFileSync, realpathSync } from "node:fs";
import { basename, dirname, extname, isAbsolute, join, relative, resolve, sep } from "node:path";

const SOURCE_EXTENSIONS = new Set(
	"ts tsx mts cts js jsx mjs cjs py pyi rb rs go java kt kts scala c h cc cpp hpp cs fs fsx swift m mm php lua sh bash zsh fish ps1 r jl ex exs erl hrl hs clj cljs vue svelte astro html htm css scss sass less json jsonc jsonl yaml yml toml ini conf xml svg sql csv graphql gql proto md mdx markdown rst txt adoc asciidoc".split(
		" ",
	),
);

const REPOSITORY_GIT_ENV = new Set(
	"GIT_ALTERNATE_OBJECT_DIRECTORIES GIT_CONFIG GIT_CONFIG_PARAMETERS GIT_CONFIG_COUNT GIT_OBJECT_DIRECTORY GIT_DIR GIT_WORK_TREE GIT_IMPLICIT_WORK_TREE GIT_GRAFT_FILE GIT_INDEX_FILE GIT_NO_REPLACE_OBJECTS GIT_REPLACE_REF_BASE GIT_PREFIX GIT_SHALLOW_FILE GIT_COMMON_DIR GIT_NAMESPACE GIT_CEILING_DIRECTORIES GIT_DISCOVERY_ACROSS_FILESYSTEM".split(
		" ",
	),
);

export interface BudgetWorkspace {
	root: string;
	commonDir: string;
}

export interface ProposedBudgetFile {
	path: string;
	content: string | null;
}

/** A path is absent when it is missing, or a directory on the way to it is missing or no longer a directory. */
export function isMissingPath(error: unknown): boolean {
	return error instanceof Error && "code" in error && (error.code === "ENOENT" || error.code === "ENOTDIR");
}

export function budgetPathExists(path: string): boolean {
	try {
		lstatSync(path);
		return true;
	} catch (error) {
		if (isMissingPath(error)) return false;
		throw error;
	}
}

function runGit(cwd: string, args: string[], input?: string) {
	const env: NodeJS.ProcessEnv = { ...process.env, GIT_OPTIONAL_LOCKS: "0", LC_ALL: "C" };
	for (const key of Object.keys(env)) {
		if (REPOSITORY_GIT_ENV.has(key) || /^GIT_CONFIG_(?:KEY|VALUE)_/.test(key)) delete env[key];
	}
	// A repository's core.fsmonitor setting names a command; hooks must not run it.
	const result = spawnSync("git", ["-c", "core.fsmonitor=false", ...args], {
		cwd,
		encoding: "utf8",
		env,
		input,
		maxBuffer: 64 * 1024 * 1024,
		timeout: 10_000,
	});
	if (result.error) throw result.error;
	return result;
}

function git(cwd: string, args: string[], input?: string): string {
	const result = runGit(cwd, args, input);
	if (result.status !== 0) throw new Error(`Budget workspace inspection failed: ${result.stderr.trim()}`);
	return result.stdout;
}

export function findBudgetWorkspace(cwd: string): BudgetWorkspace | undefined {
	const directory = realpathSync(cwd);
	const result = runGit(directory, ["rev-parse", "--show-toplevel", "--git-common-dir"]);
	if (result.status !== 0) {
		if (result.stderr.includes("not a git repository")) return undefined;
		throw new Error(`Budget workspace inspection failed: ${result.stderr.trim()}`);
	}
	const [root, commonDir] = result.stdout.split(/\r?\n/);
	return { root: realpathSync(root), commonDir: realpathSync(resolve(directory, commonDir)) };
}

function gitCommonDirectory(dotGit: string): string | undefined {
	if (lstatSync(dotGit).isDirectory()) return dotGit;
	const gitdir = /^gitdir: (.+)$/m.exec(readFileSync(dotGit, "utf8"))?.[1]?.trim();
	if (!gitdir) return undefined;
	const directory = resolve(dirname(dotGit), gitdir);
	const commondir = join(directory, "commondir");
	return existsSync(commondir) ? resolve(directory, readFileSync(commondir, "utf8").trim()) : directory;
}

/**
 * A file-system test for opt-in that needs no Git process: false only when no configuration exists from `cwd` up
 * to the repository root and the repository has no active task. Any doubt answers true, leaving the decision to Git.
 */
export function mayHaveBudgets(cwd: string, marker: string): boolean {
	let start: string;
	try {
		start = realpathSync(cwd);
	} catch {
		return true;
	}
	for (let directory = start; ; directory = dirname(directory)) {
		if (existsSync(join(directory, ".draht", "budgets.json"))) return true;
		const dotGit = join(directory, ".git");
		if (existsSync(dotGit)) {
			try {
				const common = gitCommonDirectory(dotGit);
				return common === undefined || existsSync(join(common, marker));
			} catch {
				return true;
			}
		}
		if (dirname(directory) === directory) return false;
	}
}

/** The commit checked out in a worktree, or null on a branch without commits. */
export function headCommit(workspace: BudgetWorkspace): string | null {
	const result = runGit(workspace.root, ["rev-parse", "--verify", "--quiet", "HEAD^{commit}"]);
	return result.status === 0 ? result.stdout.trim() : null;
}

/** Paths marked linguist-generated by the .gitattributes in `commit`; later attribute edits cannot exclude files. */
export function generatedPaths(
	workspace: BudgetWorkspace,
	commit: string | null,
	paths: readonly string[],
): Set<string> {
	const generated = new Set<string>();
	if (!commit || paths.length === 0) return generated;
	const fields = git(
		workspace.root,
		["check-attr", `--source=${commit}`, "-z", "--stdin", "linguist-generated"],
		`${paths.join("\0")}\0`,
	).split("\0");
	for (let index = 0; index + 2 < fields.length; index += 3) {
		if (fields[index + 2] === "set" || fields[index + 2] === "true") generated.add(fields[index]);
	}
	return generated;
}

export function isBudgetRelativePath(path: string): boolean {
	return path.length > 0 && !isAbsolute(path) && path.split(/[\\/]/).every((part) => part !== ".." && part !== ".git");
}

/** Tracked and untracked, non-ignored paths outside nested repositories. */
export function listWorkspacePaths(workspace: BudgetWorkspace): Set<string> {
	const paths = new Set(
		git(workspace.root, ["ls-files", "--cached", "--others", "--exclude-standard", "-z"]).split("\0").filter(Boolean),
	);
	for (const path of paths) {
		if (!isBudgetRelativePath(path)) throw new Error(`Invalid budget snapshot path: ${path}`);
	}
	return paths;
}

/** Reports whether a repository-relative path passes through a symlink, remembering directories it has checked. */
export function symlinkCheck(root: string): (path: string) => boolean {
	const directories = new Map<string, boolean>();
	const linked = (path: string): boolean => {
		const parent = dirname(path);
		let inherited = false;
		if (parent !== ".") {
			inherited = directories.get(parent) ?? linked(parent);
			directories.set(parent, inherited);
		}
		if (inherited) return true;
		try {
			return lstatSync(join(root, path)).isSymbolicLink();
		} catch (error) {
			if (isMissingPath(error)) return false;
			throw error;
		}
	};
	return linked;
}

/** Resolves symlinks in the existing part of a path, so a symlinked session directory names the repository's files. */
export function canonicalBudgetPath(cwd: string, path: string): string {
	const missing: string[] = [];
	let existing = resolve(cwd, path);
	while (!existsSync(existing) && dirname(existing) !== existing) {
		missing.unshift(basename(existing));
		existing = dirname(existing);
	}
	return join(realpathSync(existing), ...missing);
}

/**
 * The repository-relative path of a canonical edit target, or undefined when the target is outside the files
 * budgets measure: outside the repository, inside Git metadata or a nested repository, or ignored by Git.
 */
export function budgetFilePath(workspace: BudgetWorkspace, target: string): string | undefined {
	const file = relative(workspace.root, target);
	if (!isBudgetRelativePath(file)) return undefined;
	for (let parent = dirname(target); parent !== workspace.root; parent = dirname(parent)) {
		if (budgetPathExists(join(parent, ".git"))) return undefined;
	}
	const ignored = runGit(workspace.root, ["check-ignore", "-q", "--", file]);
	if (ignored.status === 0) return undefined;
	if (ignored.status !== 1) throw new Error(`Budget ignore inspection failed: ${ignored.stderr.trim()}`);
	return file.split(sep).join("/");
}

export function isSourcePath(path: string): boolean {
	return (
		SOURCE_EXTENSIONS.has(extname(path).slice(1).toLowerCase()) || /^(dockerfile|makefile)$/i.test(basename(path))
	);
}
