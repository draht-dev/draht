import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, realpathSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { gunzipSync, gzipSync } from "node:zlib";
import { build } from "esbuild";
import cl100kRanks from "gpt-tokenizer/bpeRanks/cl100k_base";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const targets = [
	"packages/coding-agent/hooks/checks",
	"packages/draht-claude/scripts",
	"packages/draht-codex/scripts",
];
const vocabularyAsset = "budgets-cl100k.json.gz";
// Resolves dependencies the way the bundled sources do, under both hoisted and isolated package layouts.
const requireFromRuntime = createRequire(resolve(root, "packages/coding-agent/src/core/budgets/policy.ts"));
const vocabularyModule = realpathSync(fileURLToPath(import.meta.resolve("gpt-tokenizer/bpeRanks/cl100k_base")));
const encodingModule = realpathSync(fileURLToPath(import.meta.resolve("gpt-tokenizer/encoding/cl100k_base")));

// The packaged encoding module builds its encoder on import. This stand-in defers that to the first measurement,
// so hooks in repositories without budgets never decompress the vocabulary.
const LAZY_ENCODING = `import { GptEncoding } from "../GptEncoding.js";
import loadBudgetVocabulary from "../bpeRanks/cl100k_base.js";

let encoding;
export function countTokens(text, options) {
  encoding ??= GptEncoding.getEncodingApi("cl100k_base", loadBudgetVocabulary);
  return encoding.countTokens(text, options);
}
`;

function vocabularyLoader(bytes) {
	const hash = createHash("sha256").update(bytes).digest("hex");
	return `import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { gunzipSync } from "node:zlib";

export default function loadBudgetVocabulary() {
  const path = join(__dirname, "${vocabularyAsset}");
  try {
    const bytes = gunzipSync(readFileSync(path), { maxOutputLength: ${bytes.length} });
    if (createHash("sha256").update(bytes).digest("hex") !== "${hash}") {
      throw new Error("Vocabulary checksum mismatch");
    }
    return JSON.parse(bytes.toString("utf8"));
  } catch (error) {
    throw new Error(\`Budget tokenizer vocabulary missing or corrupt: \${path}\`, { cause: error });
  }
}
`;
}

/** The installed package directory; nested folders such as gpt-tokenizer's cjs/ carry the package name too. */
function packageDirectory(name) {
	const entry = requireFromRuntime.resolve(name);
	const marker = `${sep}node_modules${sep}${name.split("/").join(sep)}${sep}`;
	const index = entry.lastIndexOf(marker);
	if (index < 0) throw new Error(`Cannot locate the ${name} package from ${entry}`);
	return entry.slice(0, index + marker.length - 1);
}

function sameVocabulary(asset, vocabulary) {
	try {
		return gunzipSync(readFileSync(asset)).equals(vocabulary);
	} catch {
		return false;
	}
}

export function syncBudgetPrompt({ check = false } = {}) {
	const source = readFileSync(resolve(root, "skills/budget/command.md"), "utf8");
	const content = source.replaceAll("<PLUGIN_ROOT>/scripts/budgets-runtime.cjs", "<BUDGET_RUNTIME>");
	// Outside prompts/, which the native host loads as slash-command templates next to its own /budget command.
	const file = resolve(root, "packages/coding-agent/hooks/checks/budget-command.md");
	if (existsSync(file) && readFileSync(file, "utf8") === content) return true;
	if (check) {
		console.error(`Budget prompt drift: ${file}`);
		return false;
	}
	mkdirSync(dirname(file), { recursive: true });
	writeFileSync(file, content);
	return true;
}

export async function syncBudgetRuntime({ check = false } = {}) {
	const vocabulary = Buffer.from(JSON.stringify(cl100kRanks));
	let vocabularyReplaced = false;
	let encodingReplaced = false;
	const result = await build({
		absWorkingDir: root,
		entryPoints: ["packages/coding-agent/src/core/budgets/cli.ts"],
		bundle: true,
		preserveSymlinks: true,
		write: false,
		platform: "node",
		format: "cjs",
		target: "node22",
		legalComments: "eof",
		banner: { js: "// Generated by scripts/sync-budgets-runtime.mjs. Do not edit." },
		plugins: [{
			name: "budget-vocabulary-asset",
			setup(builder) {
				builder.onLoad({ filter: /[\\/]bpeRanks[\\/]cl100k_base\.js$/ }, ({ path }) => {
					if (realpathSync(path) !== vocabularyModule) return;
					vocabularyReplaced = true;
					return { loader: "js", contents: vocabularyLoader(vocabulary) };
				});
				builder.onLoad({ filter: /[\\/]encoding[\\/]cl100k_base\.js$/ }, ({ path }) => {
					if (realpathSync(path) !== encodingModule) return;
					encodingReplaced = true;
					return { loader: "js", contents: LAZY_ENCODING, resolveDir: dirname(path) };
				});
			},
		}],
	});
	if (!vocabularyReplaced || !encodingReplaced) throw new Error("Budget tokenizer modules were not replaced");
	const license = ["gpt-tokenizer", "diff"].map((name) => {
		const location = ["LICENSE", "LICENSE.txt"].map((file) => join(packageDirectory(name), file)).find(existsSync);
		if (!location) throw new Error(`Missing bundled dependency license: ${name}`);
		return `${name}\n${readFileSync(location, "utf8")}`;
	}).join("\n\n") + "\n\n" + readFileSync(join(packageDirectory("gpt-tokenizer"), "data/Unicode-LICENSE.txt"), "utf8");
	// esbuild's module path comments follow the install layout: the isolated linker reaches diff through
	// packages/coding-agent/node_modules, the release workflow's hoisted linker through node_modules.
	const bundle = result.outputFiles[0].text.replace(/^\/\/ (?:packages\/[^/\n]+\/)+node_modules\//gm, "// node_modules/");
	const assets = new Map([
		["budgets-runtime.cjs", Buffer.from(bundle)],
		["budgets-runtime.LICENSE", Buffer.from(license)],
	]);
	let synchronized = syncBudgetPrompt({ check });
	for (const target of targets) {
		for (const [name, content] of assets) {
			const file = resolve(root, target, name);
			if (existsSync(file) && readFileSync(file).equals(content)) continue;
			if (check) {
				console.error(`Budget runtime drift: ${file}`);
				synchronized = false;
			} else {
				mkdirSync(dirname(file), { recursive: true });
				writeFileSync(file, content);
			}
		}
		// Compressed bytes differ between zlib builds, so drift is judged on the decompressed vocabulary.
		const asset = resolve(root, target, vocabularyAsset);
		if (existsSync(asset) && sameVocabulary(asset, vocabulary)) continue;
		if (check) {
			console.error(`Budget runtime drift: ${asset}`);
			synchronized = false;
		} else {
			writeFileSync(asset, gzipSync(vocabulary, { level: 9 }));
		}
	}
	return synchronized;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	if (!await syncBudgetRuntime({ check: process.argv.includes("--check") })) process.exitCode = 1;
}
